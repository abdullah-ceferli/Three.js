import assert from 'node:assert/strict';
import { migrateInventory, inventoryAction, insertItem, validateInventory, equippedStack } from '../src/shared/inventoryState.js';
import { groundHeight, playerHeight, isSwimming, ISLAND_RESOURCES } from '../src/shared/worldLayout.js';

let state = migrateInventory();
assert.equal(state.resources.stone, 1);assert.equal(state.resources.wood, 0);
assert.equal(state.hotbar.length, 5);assert.equal(state.inventorySlots.length, 15);
const stone = state.hotbar[0];
state = inventoryAction(state,{type:'move',fromArea:'hotbar',fromIndex:0,toArea:'inventory',toIndex:2,itemId:stone});
assert.equal(state.hotbar[0],null);assert.equal(state.inventorySlots[2],stone);assert.equal(equippedStack(state),null);
state = inventoryAction(state,{type:'move',fromArea:'inventory',fromIndex:2,toArea:'hotbar',toIndex:4,itemId:stone});
assert.equal(state.inventorySlots[2],null);assert.equal(state.hotbar[4],stone);
for(let index=0;index<5;index++)assert.equal(inventoryAction(state,{type:'select',index}).selectedHotbarIndex,index);
assert.throws(()=>inventoryAction(state,{type:'select',index:5}));
assert.throws(()=>inventoryAction(state,{type:'move',fromArea:'hotbar',fromIndex:4,toArea:'inventory',toIndex:0,itemId:'stale'}));
state=migrateInventory({resources:{wood:100,stone:50,rope:6,leaves:1001},tools:[],hotbar:[],inventorySlots:[]});
assert.equal(Object.values(state.items).filter(x=>x.type==='leaves').length,2);
state=inventoryAction(state,{type:'craft',recipeId:'stone_hatchet'});
state=inventoryAction(state,{type:'craft',recipeId:'stone_hatchet'});
const tools=Object.values(state.items).filter(x=>x.type==='stone_hatchet');
assert.equal(tools.length,2);assert.notEqual(tools[0].id,tools[1].id);assert.equal(tools[0].durability,300);
assert.equal(state.resources.wood,0);assert.equal(state.resources.stone,0);assert.equal(state.resources.rope,0);
const before=JSON.stringify(state);assert.throws(()=>inventoryAction(state,{type:'craft',recipeId:'stone_hatchet'}));assert.equal(JSON.stringify(state),before);
const index=state.inventorySlots.indexOf(tools[0].id);
state=inventoryAction(state,{type:'move',fromArea:'inventory',fromIndex:index,toArea:'hotbar',toIndex:0});
state=inventoryAction(state,{type:'harvest',resource:'wood',amount:32,toolId:tools[0].id,now:1000});
assert.equal(state.items[tools[0].id].durability,299);assert.equal(state.items[tools[1].id].durability,300);
state.items[tools[0].id].durability=0;assert.equal(equippedStack(state),null);
const full=migrateInventory({resources:{},tools:[],hotbar:[],inventorySlots:[]});insertItem(full,'stone_hatchet',20);validateInventory(full);
const snapshot=JSON.stringify(full);assert.throws(()=>inventoryAction(full,{type:'harvest',resource:'stone',amount:1,now:1}));assert.equal(JSON.stringify(full),snapshot);
const legacy=migrateInventory({resources:{stone:123,wood:56},tools:['axe'],hotbar:['stone',null,null,null,null,'wood'],inventorySlots:['stone']});
assert.equal(legacy.resources.stone,123);assert.equal(legacy.resources.wood,56);assert.equal(legacy.hotbar.length,5);
assert.equal(new Set([...legacy.hotbar,...legacy.inventorySlots].filter(Boolean)).size,Object.keys(legacy.items).length);
assert.ok(groundHeight(0,0)>0);assert.ok(isSwimming(400,0));assert.ok(isSwimming(10000,10000));assert.equal(playerHeight(10000,10000),-1.25);
assert.ok(ISLAND_RESOURCES.filter(x=>x.type==='leaf').length>100);
assert.equal(new Set(ISLAND_RESOURCES.map(x=>x.id)).size,ISLAND_RESOURCES.length);
console.log('PASS: physical slots, stale-move rejection, five-slot selection, legacy migration, overflow, crafting rollback, distinct tool durability, broken tools, island/swimming.');
